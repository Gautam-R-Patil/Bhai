// Embeds the mascot (desktop/components/mascot.js + small copies of the pose
// sprites as data URIs) into src/overlay/overlay.html, which is served by the
// bot and can't load desktop assets. Run after changing the mascot:
//   node scripts/sync-overlay-mascot.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const mascotJs = fs.readFileSync(path.join(root, "desktop/components/mascot.js"), "utf8");
const spriteDir = path.join(root, "desktop/assets/mascot");
const overlayPath = path.join(root, "src/overlay/overlay.html");

// The chat bar shows Bhai at 40px; 120px keeps it sharp on Retina.
const POSES = ["hello", "hero", "thinking", "peek", "working", "typing", "celebrating", "excited", "chill", "idea"];
const sprites = {};
for (const name of POSES) {
    const png = await sharp(path.join(spriteDir, `${name}.png`))
        .resize(120, 120, { fit: "inside" })
        .png({ compressionLevel: 9 })
        .toBuffer();
    sprites[name] = `data:image/png;base64,${png.toString("base64")}`;
}

const START = "<!-- BHAI-MASCOT:START (generated by scripts/sync-overlay-mascot.mjs — do not edit) -->";
const END = "<!-- BHAI-MASCOT:END -->";
const block = `${START}
  <script>
${mascotJs}
window.BhaiMascot.setSprites(${JSON.stringify(sprites)});
  </script>
  ${END}`;

let html = fs.readFileSync(overlayPath, "utf8");
const s = html.indexOf(START.slice(0, 24));
const e = html.indexOf(END);
if (s !== -1 && e !== -1) {
    html = html.slice(0, s) + block + html.slice(e + END.length);
} else {
    html = html.replace("</head>", `  ${block}\n</head>`);
}
fs.writeFileSync(overlayPath, html);
console.log(`overlay mascot synced: ${POSES.length} sprites, ${Math.round(block.length / 1024)} KB`);
