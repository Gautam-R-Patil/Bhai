import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

export const RUNNER_FILENAME = "_runner.js";

// The bootstrap script. Runs in each worker_threads Worker.
// Receives via workerData: { handlerPath, capabilities, slug }
// Communicates via parentPort messages: { id, ok, result | error }
const RUNNER_SOURCE = String.raw`// Forge worker bootstrap — DO NOT EDIT. Regenerated by ATLAS on boot.
"use strict";
const { parentPort, workerData } = require("node:worker_threads");
const path = require("node:path");
const realFs = require("node:fs");

class ForgeCapabilityDenied extends Error {
    constructor(capability, attempted) {
        super("forge capability denied: " + capability + " for " + attempted);
        this.name = "ForgeCapabilityDenied";
        this.capability = capability;
        this.attempted = attempted;
    }
}

// ── Module._resolveFilename denylist ──
const Module = require("node:module");
const REQUIRE_DENYLIST = new Set([
    "child_process", "cluster", "worker_threads", "v8", "perf_hooks", "inspector",
    "v8/tools", "node:child_process", "node:cluster", "node:worker_threads",
    "node:v8", "node:perf_hooks", "node:inspector",
]);
const _origResolve = Module._resolveFilename;
Module._resolveFilename = function patched(request, ...rest) {
    if (REQUIRE_DENYLIST.has(request)) {
        throw new ForgeCapabilityDenied("require", request);
    }
    return _origResolve.call(this, request, ...rest);
};

// ── Hard-coded denylist paths (override user grants) ──
const HARD_DENY_PATHS = [
    "/etc/passwd", "/etc/shadow", "/etc/sudoers",
    "/.ssh/", "/.aws/", "/.gnupg/",
];

function pathIsHardDenied(p) {
    const canonical = realFs.existsSync(p) ? realFs.realpathSync(p) : p;
    return HARD_DENY_PATHS.some(d => canonical.includes(d));
}

// Encrypted-source enforcement: never let a handler read these
function pathIsSource(p) {
    return /\b(src|native|prompts|convex)\b\//.test(p);
}

// ── Patch fs to enforce fs_read / fs_write capabilities ──
const caps = workerData.capabilities || { fs_read: [], fs_write: [], net: [], exec: [] };

function expandHome(p) {
    if (typeof p !== "string") return p;
    if (p.startsWith("~/")) return path.join(require("node:os").homedir(), p.slice(2));
    return p;
}

function fsReadAllowed(target) {
    const t = path.resolve(expandHome(target));
    if (pathIsHardDenied(t)) return false;
    if (pathIsSource(t)) return false;
    return (caps.fs_read || []).some(prefix => t.startsWith(path.resolve(expandHome(prefix))));
}

function fsWriteAllowed(target) {
    const t = path.resolve(expandHome(target));
    if (pathIsHardDenied(t)) return false;
    if (pathIsSource(t)) return false;
    return (caps.fs_write || []).some(prefix => t.startsWith(path.resolve(expandHome(prefix))));
}

const fsReaders = ["readFile", "readFileSync", "readdir", "readdirSync", "stat", "statSync", "createReadStream", "access", "accessSync"];
for (const m of fsReaders) {
    const orig = realFs[m];
    if (typeof orig !== "function") continue;
    realFs[m] = function (target, ...rest) {
        if (typeof target === "string" && !fsReadAllowed(target)) {
            throw new ForgeCapabilityDenied("fs.read", target);
        }
        return orig.call(this, target, ...rest);
    };
}
const fsWriters = ["writeFile", "writeFileSync", "appendFile", "appendFileSync", "unlink", "unlinkSync", "rm", "rmSync", "rmdir", "rmdirSync", "createWriteStream", "mkdir", "mkdirSync"];
for (const m of fsWriters) {
    const orig = realFs[m];
    if (typeof orig !== "function") continue;
    realFs[m] = function (target, ...rest) {
        if (typeof target === "string" && !fsWriteAllowed(target)) {
            throw new ForgeCapabilityDenied("fs.write", target);
        }
        return orig.call(this, target, ...rest);
    };
}

// ── Patch fetch / http / https for net capability ──
const allowedHosts = new Set(caps.net || []);
const _origFetch = globalThis.fetch;
globalThis.fetch = async function (url, init) {
    try {
        const u = typeof url === "string" ? new URL(url) : new URL(url.url || String(url));
        if (!allowedHosts.has(u.hostname)) {
            throw new ForgeCapabilityDenied("net", u.hostname);
        }
    } catch (e) {
        if (e instanceof ForgeCapabilityDenied) throw e;
        // Malformed URL — treat as denied
        throw new ForgeCapabilityDenied("net", String(url));
    }
    return _origFetch.call(this, url, init);
};

// ── Load the handler ──
let handler;
try {
    handler = require(workerData.handlerPath);
    if (typeof handler !== "function" && typeof handler?.default === "function") handler = handler.default;
    if (typeof handler !== "function") {
        throw new Error("handler module did not export a function");
    }
} catch (err) {
    parentPort.postMessage({ id: "__boot__", ok: false, error: { kind: "boot_failure", message: err.message, stack: err.stack } });
    process.exit(1);
}

parentPort.postMessage({ id: "__boot__", ok: true });

parentPort.on("message", async (msg) => {
    if (!msg || typeof msg !== "object" || typeof msg.id !== "string") return;
    if (msg.kind === "shutdown") { process.exit(0); }

    try {
        const result = await Promise.race([
            handler(msg.input || {}),
            new Promise((_, rej) => setTimeout(() => rej(new Error("worker timeout (handler internal)")), 55000)),
        ]);
        parentPort.postMessage({ id: msg.id, ok: true, result });
    } catch (err) {
        const kind = err instanceof ForgeCapabilityDenied ? "capability_denied" : "handler_error";
        parentPort.postMessage({
            id: msg.id, ok: false,
            error: {
                kind,
                message: err && err.message ? err.message : String(err),
                capability: err && err.capability,
                attempted: err && err.attempted,
                stack: err && err.stack,
            },
        });
    }
});
`;

export async function writeRunnerAsset(dir: string): Promise<void> {
    if (!existsSync(dir)) await mkdir(dir, { recursive: true });
    await writeFile(join(dir, RUNNER_FILENAME), RUNNER_SOURCE, { encoding: "utf-8", mode: 0o644 });
}

export function getRunnerSource(): string {
    return RUNNER_SOURCE;
}
